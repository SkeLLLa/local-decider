import { build } from 'esbuild';
// Bundle src/main.ts into the plugin's committed, dependency-free hook runner, and src/mod/register.ts
// into the Claude Code mod it loads (no node: imports). The output is
// deterministic (no timestamps, no absolute paths) so CI can rebuild it and diff the result.
import { readFileSync, statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outfile = resolve(here, '../../plugins/local-decider/dist/local-decider-hook.mjs');

await build({
  entryPoints: [resolve(here, 'src/main.ts')],
  outfile,
  absWorkingDir: here,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  conditions: ['source'],
  minify: false,
  legalComments: 'inline',
  sourcemap: false,
  treeShaking: true,
  ignoreAnnotations: false,
  charset: 'utf8',
  banner: {
    js: '#!/usr/bin/env node\n// Generated by packages/hooks/build.mjs from packages/hooks/src. Do not edit.',
  },
  logLevel: 'warning',
});

console.log(`wrote ${outfile} (${statSync(outfile).size} bytes)`);

// The mod runs inside Claude Code's mod host, not Node: platform-neutral, ESM, readable.
const modOutfile = resolve(here, '../../plugins/local-decider/hooks/local-decider-auto-mode.mjs');
await build({
  entryPoints: [resolve(here, 'src/mod/register.ts')],
  outfile: modOutfile,
  absWorkingDir: here,
  bundle: true,
  platform: 'neutral',
  format: 'esm',
  target: 'es2022',
  conditions: ['source'],
  mainFields: ['module', 'main'],
  // core's barrel imports node:crypto for modules the mod never uses; tree shaking drops them.
  external: ['node:*'],
  minify: false,
  legalComments: 'inline',
  sourcemap: false,
  treeShaking: true,
  charset: 'utf8',
  banner: {
    js: '// Generated by packages/hooks/build.mjs from packages/hooks/src/mod. Do not edit.',
  },
  logLevel: 'warning',
});

if (/\bnode:/.test(readFileSync(modOutfile, 'utf8'))) {
  throw new Error(`${modOutfile} must not import node: modules`);
}
console.log(`wrote ${modOutfile} (${statSync(modOutfile).size} bytes)`);
