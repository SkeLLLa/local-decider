import { build } from 'esbuild';
// Bundle src/main.ts into the plugin's committed, dependency-free hook runner. The output is
// deterministic (no timestamps, no absolute paths) so CI can rebuild it and diff the result.
import { statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outfile = resolve(here, '../../plugins/local-decider/dist/hook.mjs');

await build({
  entryPoints: [resolve(here, 'src/main.ts')],
  outfile,
  absWorkingDir: here,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  conditions: ['source'],
  minify: false,
  legalComments: 'inline',
  sourcemap: false,
  treeShaking: true,
  ignoreAnnotations: false,
  charset: 'utf8',
  banner: {
    js: '#!/usr/bin/env node\n// Generated by packages/hooks/build.mjs from packages/hooks/src. Do not edit.',
  },
  logLevel: 'warning',
});

console.log(`wrote ${outfile} (${statSync(outfile).size} bytes)`);
